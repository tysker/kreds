import {copyFileSync, mkdirSync} from 'node:fs'
import {defineConfig, type Plugin} from 'vite'
import react from '@vitejs/plugin-react'

// core-crypto ships its WebAssembly file inside node_modules.
// The browser can only load files the dev server serves, so we copy it into public/.
const WASM_SOURCE = 'node_modules/@wireapp/core-crypto/dist/autogenerated/wasm-bindgen/index_bg.wasm'
const WASM_TARGET_DIR = 'public/core-crypto'

function copyCoreCryptoWasm(): Plugin {
    const copy = () => {
        mkdirSync(WASM_TARGET_DIR, {recursive: true})
        copyFileSync(WASM_SOURCE, `${WASM_TARGET_DIR}/index_bg.wasm`)
    }
    // 'config' runs before the dev server starts, so the file exists when Vite lists public/.
    return {name: 'copy-core-crypto-wasm', config: copy}
}

export default defineConfig({
    plugins: [copyCoreCryptoWasm(), react()],
})